export function searchGuides(query: string, category = "All") {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  return GUIDE_TOPICS.filter(
    (t) =>
      (category === "All" || t.category === category) &&
      words.every((w) =>
        `${t.title} ${t.what} ${t.how} ${t.tip}`.toLowerCase().includes(w),
      ),
  );
}
